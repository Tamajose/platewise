"""Make the repeatable Supabase seed from the mobile demo dataset."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
NUTRIENTS = ("protein_g", "carbohydrate_g", "fat_g", "fiber_g", "sodium_mg")


def sql(value):
    if value is None:
        return "null"
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    return str(value)


def row(columns):
    return "(" + ",".join(map(sql, columns)) + ")"


def generate():
    source = ROOT / "app/assets/data/seeded_menus.json"
    restaurants = json.loads(source.read_text())
    restaurant_rows, menu_rows = [], []
    for venue in restaurants:
        restaurant_rows.append(row([venue[k] for k in ("id", "name", "latitude", "longitude")]
                                   + ["seeded", "PlateWise synthetic menus", "PlateWise team", None]))
        for item in venue["menu"]:
            menu_rows.append(row([item["id"], venue["id"]] +
                                 [item[k] for k in ("name", "portion", "calorie_low", "calorie_high")] +
                                 [item.get(k) for k in NUTRIENTS]))
    return "".join([
        "-- Generated by tools/generate_seed.py. Fictional venues and portions.\n",
        "insert into public.restaurants(id,name,latitude,longitude,dataset,source,attribution,last_verified_at) values\n",
        ",\n".join(restaurant_rows), "\non conflict(id) do nothing;\n",
        "insert into public.menu_items(id,restaurant_id,name,portion,calorie_low,calorie_high,",
        ",".join(NUTRIENTS), ") values\n", ",\n".join(menu_rows), "\non conflict(id) do nothing;\n",
    ])


if __name__ == "__main__":
    (ROOT / "supabase/seed.sql").write_text(generate())
